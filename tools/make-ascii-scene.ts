// Build-time: renders the Atrium lair art as a tonal ASCII picture into web/atrium/ascii-scene.js (committed).
// Run: bun tools/make-ascii-scene.ts   (needs ImageMagick). The runtime never decodes an image.
import { join } from "node:path";
import { writeFileSync } from "node:fs";

const ROOT = join(import.meta.dir, "..", "web", "atrium");
const COLS = 192, ROWS = 66; // glyph cells are ~0.6 wide : 1 high, so this is ~16:9
const RAMP = " .:-=+*#%@";
const p = Bun.spawnSync(["magick", join(ROOT, "art", "caesaros-lair-scene.webp"), "-colorspace", "Gray", "-filter", "Lanczos", "-resize", `${COLS}x${ROWS}!`, "-contrast-stretch", "3%x0.4%", "-gamma", "0.75", "-depth", "8", "gray:-"]);
if (p.exitCode !== 0) throw new Error(p.stderr.toString());
const px = p.stdout;
if (px.length !== COLS * ROWS) throw new Error(`unexpected size ${px.length}`);
const rows: string[] = [];
for (let y = 0; y < ROWS; y++) {
  let s = "";
  for (let x = 0; x < COLS; x++) s += RAMP[Math.min(RAMP.length - 1, Math.floor((px[y * COLS + x] / 256) * RAMP.length))];
  rows.push(s);
}
writeFileSync(join(ROOT, "ascii-scene.js"), `// GENERATED by tools/make-ascii-scene.ts from art/caesaros-lair-scene.webp. Do not edit by hand.\nwindow.caesarosAsciiScene = ${JSON.stringify({ ramp: RAMP, cols: COLS, rows }, null, 0).replace('"rows":[', '"rows":[\n').replace(/","/g, '",\n"')};\n`);
console.log(`wrote ascii-scene.js ${COLS}x${ROWS}`);
