// Legio Dot: the Legio icons as a square-pixel dot matrix (the idea of Nothing's dot-matrix glyphs, in our language:
// square dots like the UI corners, one ember accent dot per icon). Generated from packs/icons/legio so the two stay in step.
// Needs Playwright only to rasterise the vectors once; the output is a plain SVG sprite.
// Run: node tools/make-legio-dot.mjs
import { createRequire } from "module";
import fs from "fs";
const HOME = process.env.HOME ?? ""; // paths under $HOME instead of one person's home
const require = createRequire(process.env.PLAYWRIGHT_DIR ?? `${HOME}/.local/share/mise/installs/playwright/latest/node_modules/`);
const { chromium } = require("playwright");
const SRC = new URL("../packs/icons/legio/legio-icons.svg", import.meta.url).pathname;
const OUT = new URL("../packs/icons/legio-dot/", import.meta.url).pathname;
const N = 16;                                  // 16 x 16 dots per icon
const sprite = fs.readFileSync(SRC, "utf8");
const names = [...sprite.matchAll(/<symbol id="i-([a-z-]+)"[^>]*>(.*?)<\/symbol>/gs)].map((m) => [m[1], m[2]]);
const b = await chromium.launch({ executablePath: process.env.CHROME ?? `${HOME}/.cache/ms-playwright/chromium-1254/chrome-linux64/chrome` });
const p = await b.newPage();
const result = await p.evaluate(async ({ names, N }) => {
  const S = 160, cell = S / N;                   // rasterise at 160 px, sample each cell
  const draw = (inner, onlyNodes) => new Promise((res) => {
    const body = onlyNodes ? inner.replace(/<g[^>]*>.*?<\/g>/s, "") : inner.replace(/<rect[^>]*\/>/g, "");
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="${S}" height="${S}">${body.replace(/currentColor/g, "#000").replace(/var\(--icon-accent,currentColor\)/g, "#000")}</svg>`;
    const img = new Image(); img.onload = () => { const c = document.createElement("canvas"); c.width = c.height = S; const x = c.getContext("2d"); x.drawImage(img, 0, 0, S, S); res(x.getImageData(0, 0, S, S).data); };
    img.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(svg);
  });
  const cover = (data, cx, cy) => { let a = 0; for (let y = 0; y < cell; y++) for (let x = 0; x < cell; x++) a += data[(((cy * cell + y) | 0) * S + ((cx * cell + x) | 0)) * 4 + 3]; return a / (cell * cell * 255); };
  const out = {};
  for (const [name, inner] of names) {
    const line = await draw(inner, false), nodes = await draw(inner, true), cells = [];
    for (let cy = 0; cy < N; cy++) for (let cx = 0; cx < N; cx++) {
      const n = cover(nodes, cx, cy), l = cover(line, cx, cy);
      if (n > 0.2) cells.push([cx, cy, 1]); else if (l > 0.26) cells.push([cx, cy, 0]);
    }
    out[name] = cells;
  }
  return out;
}, { names, N });
await b.close();
fs.mkdirSync(OUT, { recursive: true });
const pitch = 24 / N, dot = pitch * 0.74, off = (pitch - dot) / 2;
let svg = '<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Legio Dot. Square-pixel dot matrix of the Legio icons, 16 by 16, one accent dot. Generated by tools/make-legio-dot.mjs -->\n';
for (const [name, cells] of Object.entries(result)) {
  const base = cells.filter((c) => !c[2]).map(([x, y]) => `M${(x * pitch + off).toFixed(2)} ${(y * pitch + off).toFixed(2)}h${dot.toFixed(2)}v${dot.toFixed(2)}h-${dot.toFixed(2)}z`).join("");
  const acc = cells.filter((c) => c[2]).map(([x, y]) => `<rect x="${(x * pitch + off).toFixed(2)}" y="${(y * pitch + off).toFixed(2)}" width="${dot.toFixed(2)}" height="${dot.toFixed(2)}" fill="var(--icon-accent,currentColor)"/>`).join("");
  svg += `<symbol id="i-${name}" viewBox="0 0 24 24"><path fill="currentColor" d="${base}"/>${acc}</symbol>\n`;
}
svg += "</svg>\n";
fs.writeFileSync(OUT + "legio-dot-icons.svg", svg);
const m = JSON.parse(fs.readFileSync(new URL("../packs/icons/legio/manifest.json", import.meta.url).pathname, "utf8"));
fs.writeFileSync(OUT + "manifest.json", JSON.stringify({ ...m, id: "legio-dot", name: "Legio Dot", file: "legio-dot-icons.svg" }, null, 2));
console.log(Object.keys(result).length, "icons,", fs.statSync(OUT + "legio-dot-icons.svg").size, "bytes");
