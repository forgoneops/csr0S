export const DICTS: Record<Lang, Dict> = { en, pl };
export const LANGS: Lang[] = ["en", "pl"];

/** Every key in every language: the language test compares these sets. */
export const allKeys = (lang: Lang) => Object.keys(DICTS[lang]).sort();

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[lang][key] ?? DICTS.en[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw;
}

/** Text for a code the server sent ("timeout", "http_429", ...). A code with no translation never reaches the screen
 *  as a raw key: a status code gets one generic line with its number, anything else the caller's fallback. */
export function codeText(lang: Lang, prefix: string, code: string | null | undefined, fallbackKey: string): string {
  const key = `${prefix}.${code ?? ""}`;
  if (code && (key in DICTS[lang] || key in DICTS.en)) return translate(lang, key);
  const http = /^http_(\d{3})$/.exec(code ?? "");
  if (http && `${prefix}.http_other` in DICTS.en) return translate(lang, `${prefix}.http_other`, { n: http[1] });
  return translate(lang, fallbackKey);
}
